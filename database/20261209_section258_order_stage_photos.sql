-- Section 258: Private, explicitly confirmed photos linked to a single KDS item.
-- Customer delivery of these photos is intentionally a separate future workflow.
CREATE TABLE glasses_order_stage_photos (
  id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
  organization_id BIGINT UNSIGNED NOT NULL,
  location_id BIGINT UNSIGNED NOT NULL,
  camera_config_id BIGINT UNSIGNED NOT NULL,
  camera_slot TINYINT UNSIGNED NOT NULL,
  kds_item_id BIGINT UNSIGNED NOT NULL,
  pos_check_id BIGINT UNSIGNED NOT NULL,
  public_id VARCHAR(80) NOT NULL,
  idempotency_key CHAR(36) NOT NULL,
  stage VARCHAR(24) NOT NULL,
  storage_relative_path VARCHAR(420) NOT NULL,
  mime_type VARCHAR(48) NOT NULL,
  byte_size BIGINT UNSIGNED NOT NULL,
  width INT UNSIGNED NOT NULL,
  height INT UNSIGNED NOT NULL,
  sha256 CHAR(64) NOT NULL,
  captured_at DATETIME(6) NOT NULL,
  status VARCHAR(24) NOT NULL DEFAULT 'confirmed',
  retention_until DATETIME(6) NOT NULL,
  created_by BIGINT UNSIGNED NOT NULL,
  created_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
  PRIMARY KEY (id),
  UNIQUE KEY uq_glasses_order_photo_public (organization_id,public_id),
  UNIQUE KEY uq_glasses_order_photo_idempotency (organization_id,idempotency_key),
  KEY idx_glasses_order_photo_item (organization_id,kds_item_id,stage,created_at),
  KEY idx_glasses_order_photo_check (organization_id,pos_check_id,created_at),
  KEY idx_glasses_order_photo_retention (organization_id,status,retention_until),
  CONSTRAINT fk_glasses_order_photo_org FOREIGN KEY (organization_id) REFERENCES organizations(id) ON DELETE CASCADE,
  CONSTRAINT fk_glasses_order_photo_location FOREIGN KEY (location_id) REFERENCES locations(id) ON DELETE CASCADE,
  CONSTRAINT fk_glasses_order_photo_camera FOREIGN KEY (camera_config_id) REFERENCES glasses_camera_locations(id),
  CONSTRAINT fk_glasses_order_photo_kds_item FOREIGN KEY (kds_item_id) REFERENCES kds_order_items(id),
  CONSTRAINT fk_glasses_order_photo_check FOREIGN KEY (pos_check_id) REFERENCES pos_checks(id),
  CONSTRAINT fk_glasses_order_photo_user FOREIGN KEY (created_by) REFERENCES users(id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
