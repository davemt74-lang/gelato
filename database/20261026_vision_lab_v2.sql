CREATE TABLE glasses_vision_dataset_versions (
  id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
  organization_id BIGINT UNSIGNED NOT NULL,
  public_id VARCHAR(80) NOT NULL,
  name VARCHAR(190) NOT NULL,
  version_label VARCHAR(80) NOT NULL,
  status VARCHAR(24) NOT NULL DEFAULT 'draft',
  parent_dataset_id BIGINT UNSIGNED NULL,
  mission_id BIGINT UNSIGNED NULL,
  dataset_hash CHAR(64) NULL,
  row_count INT UNSIGNED NOT NULL DEFAULT 0,
  class_count INT UNSIGNED NOT NULL DEFAULT 0,
  quality_json JSON NULL,
  manifest_json JSON NULL,
  created_by BIGINT UNSIGNED NOT NULL,
  frozen_by BIGINT UNSIGNED NULL,
  frozen_at DATETIME(6) NULL,
  created_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
  updated_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6) ON UPDATE CURRENT_TIMESTAMP(6),
  PRIMARY KEY (id),
  UNIQUE KEY uq_glasses_vision_dataset_public (organization_id,public_id),
  UNIQUE KEY uq_glasses_vision_dataset_version (organization_id,name,version_label),
  CONSTRAINT fk_glasses_vision_dataset_org FOREIGN KEY (organization_id) REFERENCES organizations(id) ON DELETE CASCADE,
  CONSTRAINT fk_glasses_vision_dataset_parent FOREIGN KEY (parent_dataset_id) REFERENCES glasses_vision_dataset_versions(id) ON DELETE SET NULL,
  CONSTRAINT fk_glasses_vision_dataset_mission FOREIGN KEY (mission_id) REFERENCES glasses_vision_training_missions(id) ON DELETE SET NULL,
  CONSTRAINT fk_glasses_vision_dataset_creator FOREIGN KEY (created_by) REFERENCES users(id),
  CONSTRAINT fk_glasses_vision_dataset_freezer FOREIGN KEY (frozen_by) REFERENCES users(id) ON DELETE SET NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE glasses_vision_dataset_items (
  id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
  organization_id BIGINT UNSIGNED NOT NULL,
  dataset_id BIGINT UNSIGNED NOT NULL,
  sample_id BIGINT UNSIGNED NOT NULL,
  split_name VARCHAR(16) NOT NULL DEFAULT 'train',
  class_label VARCHAR(190) NULL,
  source_hash CHAR(64) NOT NULL,
  created_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
  PRIMARY KEY (id),
  UNIQUE KEY uq_glasses_vision_dataset_item (dataset_id,sample_id),
  KEY idx_glasses_vision_dataset_split (organization_id,dataset_id,split_name),
  CONSTRAINT fk_glasses_vision_dataset_item_org FOREIGN KEY (organization_id) REFERENCES organizations(id) ON DELETE CASCADE,
  CONSTRAINT fk_glasses_vision_dataset_item_dataset FOREIGN KEY (dataset_id) REFERENCES glasses_vision_dataset_versions(id) ON DELETE CASCADE,
  CONSTRAINT fk_glasses_vision_dataset_item_sample FOREIGN KEY (sample_id) REFERENCES glasses_vision_training_samples(id) ON DELETE RESTRICT
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
