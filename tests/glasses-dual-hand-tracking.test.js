'use strict';
const assert=require('node:assert/strict'),fs=require('node:fs');
const core=require('../assets/js/glasses-hand-tracker.js');
const hand=(x,y,label='hand',confidence=.93)=>({label,bbox:{x,y,width:.14,height:.16},confidence});
const thing=(x,y,label='Mozzarella')=>({label,bbox:{x,y,width:.10,height:.1},confidence:.92});
const item={kdsItemPublicId:'kds-a',status:'in_progress',menu:{ingredients:[
 {name:'Sauce',canonicalName:'Sauce'}, {name:'Mozzarella',canonicalName:'Mozzarella'},
 {name:'Basil',canonicalName:'Basil'},{name:'Pepperoni',canonicalName:'Pepperoni'}]}};
const t=core.createTracker({ttlMs:1200,lostMs:200});
let v=t.step([],100,item,{});
assert.equal(v.tracks.length,2);
assert.deepEqual(v.tracks.map(x=>x.status),['ready','ready'],'two READY hand boxes');
assert.deepEqual(v.focused.map(x=>x.name),['Sauce','Mozzarella','Basil'],'three focused candidates from active KDS item');
const hands=[hand(.1,.2,'left hand'),hand(.74,.21,'right hand')];
v=t.step(hands,110,item,{},[]);
assert.equal(v.live,2,'two visible tracks');
assert.equal(v.tracks[0].status,'tracking','unfocused object does not fabricate identification');
assert.equal(v.tracks[1].status,'tracking');
const ids=v.tracks.map(x=>x.trackId);
v=t.step([hand(.73,.22,'right hand'),hand(.11,.21,'left hand')],150,item,{},[thing(.12,.24)]);
assert.deepEqual(v.tracks.map(x=>x.trackId),ids,'detector order swap preserves left/right tracks');
assert.equal(v.tracks[0].status,'identifying','object-in-hand matching is advisory and KDS scoped');
assert.equal(v.tracks[0].object.label,'Mozzarella');
v=t.step([],420,item,{});
assert.equal(v.tracks[0].status,'lost','hands go out of view without immediate track deletion');
assert.equal(v.tracks[1].status,'lost');
v=t.step([hand(.12,.22,'left hand'),hand(.72,.22,'right hand')],520,item,{});
assert.deepEqual(v.tracks.map(x=>x.trackId),ids,'quick return reacquires same two tracks');
assert.equal(v.events.filter(x=>x.type==='reacquired').length,2);
v=t.step([],1900,item,{});
assert.deepEqual(v.tracks.map(x=>x.status),['ready','ready'],'expired tracks reset to READY');
v=t.step([hand(.14,.24)],1930,item,{});
assert.notEqual(v.tracks[0].trackId,ids[0],'long absence re-registers a new track');
const scoped=core.ingredientCandidates(item,{'0:Sauce':'added'});
assert.equal(scoped[0].name,'Mozzarella','accounted ingredients excluded');
const noOrder=core.ingredientCandidates({status:'completed',...item,status:'completed'});
assert.equal(noOrder.length,0);
assert.equal(core.ingredientCandidates(null).length,0);
assert.equal(core.isHand({label:'pepperoni'}),false);
assert.equal(core.isHand({label:'hand'}),true);
assert.equal(core.validBox({x:.93,y:.8,width:.1,height:.15}),false);
assert.throws(()=>t.step([],0,item,{}),/timestamp order/i);
const stage=fs.readFileSync('glasses-simulator.php','utf8');
const ui=fs.readFileSync('assets/js/glasses-hand-tracker-ui.js','utf8');
const main=fs.readFileSync('assets/js/glasses-web-simulator.js','utf8');
assert.match(stage,/id="glassesHandState1"/);
assert.match(stage,/id="glassesHandState2"/);
assert.match(stage,/id="glassesHandBoxes"/);
assert.match(main,/const realModel=\$\('visionAdapterSelect'\)\?\.value==='onnx'/,'must be actual ONNX observations');
assert.match(main,/filtered\.filter\(d=>!core\?\.isHand\(d\)\)/,'hands never become ingredient evidence');
assert.match(main,/activeItem:item/,'KDS item drives candidate scope');
assert.match(main,/gelato-glasses-hand-reset/,'stale hand tracks cleared on camera/vision stop');
assert.doesNotMatch(ui,/fetch\(|api\(|\.submit\(/,'hands never submit KDS actions');
console.log('glasses-dual-hand-tracking=ok');