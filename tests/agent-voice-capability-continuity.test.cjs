'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const base=path.resolve(__dirname,'..');
const client=fs.readFileSync(path.join(base,'js/global-agent.js'),'utf8');
const api=fs.readFileSync(path.join(base,'api/food-monster-llm.php'),'utf8');
const runtime=fs.readFileSync(path.join(base,'includes/food-monster-b8d3-tool-runtime.php'),'utf8');
const start=client.indexOf('  function voiceSampleFromMonitor(text){');
const end=client.indexOf('  function stopVoiceMonitor(){',start);
assert(start>=0&&end>start,'live client should contain fresh per-utterance feature sampling');
// Execute the shipped sampling code with a local, memory-only monitor.
const state={voiceMonitor:{frames:[]},voiceSample:null};
let now=1_000_000;
class FakeDate {static now(){return now;}}
const collect=new Function('S','Date',client.slice(start,end)+'return voiceSampleFromMonitor;')(state,FakeDate);
const band=Array.from({length:24},(_,i)=>i===3?0.48:0.14);
for(let i=0;i<20;i++)state.voiceMonitor.frames.push({at:now-i*80,level:0.16,bands:band});
collect('Who works tomorrow?');
assert.equal(state.voiceSample.text,'Who works tomorrow?');
assert.equal(state.voiceSample.vector.length,24);
assert(Math.abs(Math.hypot(...state.voiceSample.vector)-1)<1e-8,'sample normalized like enrolled profile');
state.voiceSample=null;
state.voiceMonitor.frames=[{at:now,level:0.16,bands:band}];
collect('Short noise');
assert.equal(state.voiceSample,null,'too short an acoustic sample cannot authorize a turn');
state.voiceMonitor.frames=Array.from({length:20},(_,i)=>({at:now-i*80,level:0.001,bands:band}));
collect('Silent room');
assert.equal(state.voiceSample,null,'silence cannot provide private access');
state.voiceMonitor.frames=Array.from({length:20},(_,i)=>({at:now-10000-i*80,level:0.16,bands:band}));
collect('Stale room');
assert.equal(state.voiceSample,null,'old acoustic observations cannot be attached to later requests');
assert(client.includes("action:'verify',features:sample.vector,matchAny:false"),'fresh identity API check before each voice turn');
assert(client.includes('verification.match?.sessionUserMatch'),'only the logged-in account can unlock private tools');
assert(client.includes('S.usedVoiceEvents.has(possibleVoiceEvent)'),'server identity events cannot be replayed');
assert(client.includes('S.usedVoiceEvents.add(freshSpeakerEvent)'),'accepted identity event is consumed');
assert(client.includes('stopVoiceMonitor();stopContinuous()'),'background voice sampler cleans up on page stop');
assert(client.includes("profile.profile?.status!=='active'"),'only explicitly enrolled users are continuously sampled');
assert(api.includes("if(!$allowTools)")&&api.includes("$publicVoiceCatalogue['list_available_menu_items']"),'unknown speakers remain public-menu scoped');
assert(api.includes("'voiceIdentityRequired'"),'API exposes the true private-tool access reason');
assert(runtime.includes('list_my_gelato_capabilities'),'runtime discovery tool is advertised to LLM');
assert(runtime.includes('fm8d11_available_domains($actor)'),'capabilities based on existing permission-scoped Agent nodes');
process.stdout.write('Gelato voice tool continuity: behavioral and boundary checks passed.\n');
