'use strict';
const assert=require('node:assert/strict');
const lib=require('../js/food-monster-room-tracker.js');
let n=0;const check=(x,label)=>{assert.ok(x,label);n++;};
let clock=0,counter=0;
const make=()=>lib.create({now:()=>clock,id:()=>('r-'+String(++counter).padStart(16,'0'))});
const descriptor=(seed)=>Array.from({length:128},(_,i)=>seed+(i%5)*.001);
const p=[{email:'cook@example.test',vector:descriptor(.1)},{email:'manager@example.test',vector:descriptor(.45)}];
check(!lib.geometry([.9,.1,.2,.2]),'reject out-of-frame geometry');
check(!lib.geometry([.1,.1,-1,.2]),'reject negative width');
check(!lib.candidate(descriptor(.1),[]),'unknown without profiles');
check(lib.candidate(descriptor(.1),p)==='cook@example.test','exact descriptor accepted');
check(!lib.candidate(descriptor(.8),p),'distant face not recognized');
let t=make();const face=[{box:[.1,.1,.3,.3],descriptor:descriptor(.1)}];
let a=t.update(face,p);check(a.length===1&&a[0].localProfileEmail==='','first match insufficient');
clock+=1600;let b=t.update([{box:[.12,.11,.3,.3],descriptor:descriptor(.1)}],p);
check(b[0].trackId===a[0].trackId&&b[0].localProfileEmail==='','track maintained, second match insufficient');
clock+=1600;let c=t.update(face,p);check(c[0].localProfileEmail==='cook@example.test','three consistent detections enable provisional match');
clock+=1600;let d=t.update([{box:[.1,.1,.3,.3],descriptor:null}],p);
check(d[0].localProfileEmail==='','recognition removed when descriptor unavailable');
clock+=1700;
t.update(face,p);
check(t.trackCount===1,'track persists within TTL');
clock+=6000;t.update([],p);check(t.trackCount===0,'tracks expire after departure');
t=make();clock+=100;
const two=t.update([{box:[.05,.1,.15,.15],descriptor:descriptor(.1)},{box:[.6,.1,.15,.15],descriptor:descriptor(.45)}],p);
check(two.length===2&&two[0].trackId!==two[1].trackId,'simultaneous people tracked separately');
clock+=1700;t.update([{box:[.05,.1,.15,.15],descriptor:descriptor(.1)},{box:[.6,.1,.15,.15],descriptor:descriptor(.45)}],p);
clock+=1700;const rr=t.update([{box:[.05,.1,.15,.15],descriptor:descriptor(.1)},{box:[.6,.1,.15,.15],descriptor:descriptor(.45)}],p);
check(rr[0].localProfileEmail==='cook@example.test'&&rr[1].localProfileEmail==='manager@example.test','distinct identities remain distinct');
const impostor=t.update([{box:[.05,.1,.15,.15],descriptor:descriptor(.45)},{box:[.6,.1,.15,.15],descriptor:descriptor(.45)}],p);
check(impostor.every(x=>x.localProfileEmail===''),'changed and duplicate candidate denied');
t.clear();check(t.trackCount===0,'stop clears all tracks');
console.log('FM-G9C multi-person recognition tracker PASS ('+n+' assertions)');
