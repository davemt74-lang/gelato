'use strict';
const assert=require('node:assert/strict'),fs=require('node:fs'),vm=require('node:vm');
const src=fs.readFileSync('js/proactive-listening-commands.js','utf8');
const ctx={window:{}};vm.runInNewContext(src,ctx,{filename:'proactive-listening-commands.js'});
const c=ctx.window.GelatoProactiveCommands;assert.ok(c);
assert.equal(c.parse('Hey Gelato, Start Listening'),'start');
assert.equal(c.parse('HEY GELATO resume listening'),'start');
assert.equal(c.parse('Hey Gelato, stop listening.'),'stop');
assert.equal(c.parse('Hey Gelato pause listening please'),'stop');
assert.equal(c.parse('Hey Gelato, microphone off'),'off');
assert.equal(c.parse('Hey Gelato, stop all listening'),'off');
assert.equal(c.parse('Hey Gelato stop microphone'),'off');
assert.equal(c.parse('Start listening'),null,'microphone cannot turn on without an explicit wake phrase');
assert.equal(c.parse('stop listening'),null,'ordinary speech is not a control');
assert.equal(c.parse('Hey Gelato how many orders'),null,'only explicit controls affect listening');
assert.equal(c.parse('Gelato, start listening'),null,'truncated wake phrase must not activate');
assert.equal(c.parse('Hey Gelato, start listening to the television'),null,'partial arbitrary speech must not activate');
assert.equal(c.display({saved:true,active:false,wake:false}).code,'saved','persisted ON is not a live microphone');
assert.equal(c.display({saved:false,active:false,wake:false}).code,'off');
assert.equal(c.display({saved:false,active:false,wake:true}).code,'wake');
assert.equal(c.display({saved:true,active:true,wake:true}).code,'listening');
assert.equal(c.display({saved:true,active:true,hidden:true}).code,'paused');
assert.equal(c.display({saved:true,active:true,blocked:true}).code,'blocked');
assert.match(c.display({saved:false,wake:true}).message,/Wake Standby|wake controls|Wake/i);
console.log('proactive-listening-commands=ok');
