'use strict';
const assert=require('node:assert/strict');
const lib=require('../js/food-monster-room-tracker.js');
let checks=0,clock=0,serial=0;
const ok=(value,label)=>{assert.ok(value,label);checks++;};
const id=()=>('r-'+String(++serial).padStart(16,'0'));
const make=()=>lib.create({now:()=>clock,id});
const descriptor=s=>Array.from({length:128},(_,i)=>s+(i%7)*.0001);
const people=[{email:'one@example.test',vector:descriptor(.1)},{email:'two@example.test',vector:descriptor(.45)}];
let tracker=make();
const view=(a,b)=>tracker.update([{box:[a,.15,.15,.18],descriptor:descriptor(.1)},{box:[b,.15,.15,.18],descriptor:descriptor(.45)}],people);
let first=view(.08,.75);const firstId=first[0].trackId,secondId=first[1].trackId;
clock+=1200;view(.20,.63);
clock+=1200;view(.34,.49);
clock+=1200;let crossed=view(.55,.28);
ok(crossed[0].trackId===firstId&&crossed[1].trackId===secondId,'crossing preserves individual track IDs by descriptor');
ok(crossed[0].localProfileEmail==='one@example.test'&&crossed[1].localProfileEmail==='two@example.test','crossing preserves separately verified provisional matches');
ok(crossed[0].box[0]<.55&&crossed[0].box[0]>.34,'display boxes smooth ordinary movement');
clock+=1000;tracker.update([],people);
ok(tracker.trackCount===2,'brief occlusion retains ephemeral association');
clock+=2800;let returned=view(.63,.20);
ok(returned[0].trackId===firstId&&returned[1].trackId===secondId,'reappearance near projected positions recovers track IDs');
ok(returned.every(x=>x.localProfileEmail===''),'gap suspends identity until three fresh consistent descriptors');
clock+=1200;tracker.update([{box:[.65,.15,.15,.18],descriptor:descriptor(.1)},{box:[.18,.15,.15,.18],descriptor:descriptor(.45)}],people);
clock+=1200;let fresh=tracker.update([{box:[.67,.15,.15,.18],descriptor:descriptor(.1)},{box:[.16,.15,.15,.18],descriptor:descriptor(.45)}],people);
ok(fresh.every(x=>!!x.localProfileEmail),'identity recovers after three fresh matches');
clock+=6000;tracker.update([],people);
ok(tracker.trackCount===0,'departed tracks expire without indefinite identity persistence');
tracker=make();clock+=100;
let bare=tracker.update([{box:[.1,.1,.15,.18],descriptor:null}],people);
clock+=1200;let bareNext=tracker.update([{box:[.13,.1,.15,.18],descriptor:null}],people);
ok(bareNext[0].trackId===bare[0].trackId,'small movement tracks anonymous faces');
clock+=2500;let anonymous=tracker.update([{box:[.14,.1,.15,.18],descriptor:null}],people);
ok(anonymous[0].trackId!==bare[0].trackId,'descriptor-free reacquisition after long gap receives fresh track ID');
ok(anonymous[0].localProfileEmail==='','anonymous reacquisition cannot inherit an identity');
console.log('Agent Eyes AE4 movement, crossing and occlusion PASS ('+checks+' assertions)');
