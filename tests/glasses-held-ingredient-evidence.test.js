'use strict';
const assert=require('node:assert/strict'),fs=require('node:fs');
const {create,choices}=require('../assets/js/glasses-held-ingredient-evidence.js');
const modelSha256='a'.repeat(64);
const item={kdsItemPublicId:'ticket-item-a',status:'in_progress',menu:{ingredients:[
 {name:'Sauce'},{name:'Mozzarella'},{name:'Pepperoni'},{name:'Basil'},{name:'Olives'}]}};
const track=(slot,id,x,y)=>({slot,trackId:id,status:'tracking',bbox:{x,y,width:.12,height:.15}});
const object=(label,x,y,confidence=.93)=>({label,confidence,bbox:{x,y,width:.10,height:.09}});
const hands=[track(1,'hand-one',.13,.2),track(2,'hand-two',.69,.22)];
const engine=create();let t=1000,frame=1;
const step=(overrides={})=>engine.update({item,tracks:hands,actions:{},objects:[object('Mozzarella',.15,.22)],
 objectSeq:frame++,objectTime:t,modelSha256,now:t+=100,...overrides});
assert.deepEqual(choices(item,{}).map(x=>x.label),['Sauce','Mozzarella','Pepperoni']);
let r=step();assert.equal(r.length,1);assert.equal(r[0].status,'candidate');assert.equal(r[0].frames,1);
r=step();assert.equal(r[0].frames,2);assert.equal(r[0].status,'candidate');
r=step();assert.equal(r[0].frames,3);assert.equal(r[0].status,'review');
assert.equal(r[0].trackId,'hand-one');assert.equal(r[0].ingredientKey,'1:Mozzarella');
assert.equal(step({objectSeq:3})[0].frames,3,'duplicate model frame cannot inflate evidence');
assert.equal(step({objectSeq:frame++,objectTime:t-2000}).length,0,'old detector output rejected');
assert.equal(step({objects:[object('Chicken',.15,.22)]}).length,0,'out-of-KDS labels excluded');
assert.equal(step({objects:[object('Basil',.15,.22)]}).length,0,'focus only on first three remaining ingredients');
assert.equal(step({objects:[object('Sauce',.14,.23)]})[0].label,'Sauce');
assert.equal(step({actions:{'1:Mozzarella':'added'},objects:[object('Mozzarella',.15,.22)]}).length,0,'accounted ingredient excluded');
assert.equal(step({actions:{'0:Sauce':'added'},objects:[object('Basil',.15,.22)]})[0].label,'Basil','candidate list advances');
assert.equal(step({objects:[object('Sauce',.15,.22)],modelSha256:''}).length,0,'verified checksum required');
const crossing=create();r=crossing.update({item,tracks:[track(1,'one',.39,.2),track(2,'two',.45,.21)],
 objects:[object('Sauce',.43,.22)],objectSeq:1,objectTime:100,modelSha256,now:150});
assert.equal(r.length,0,'ambiguous object between hands rejected');
const far=create();r=far.update({item,tracks:hands,objects:[object('Sauce',.91,.87)],objectSeq:1,objectTime:100,modelSha256,now:150});
assert.equal(r.length,0,'ingredient on counter is not associated with hand');
const reset=create();reset.update({item,tracks:hands,objects:[object('Sauce',.15,.22)],objectSeq:1,objectTime:100,modelSha256,now:150});
r=reset.update({item:{...item,kdsItemPublicId:'other'},tracks:hands,objects:[object('Sauce',.15,.22)],objectSeq:2,objectTime:190,modelSha256,now:200});
assert.equal(r[0].frames,1,'new ticket cannot inherit old evidence');
r=reset.update({item,tracks:[track(1,'new-hand',.13,.2)],objects:[object('Sauce',.15,.22)],objectSeq:3,objectTime:230,modelSha256,now:250});
assert.equal(r[0].frames,1,'new hand cannot inherit old evidence');
assert.equal(reset.update({item:null,tracks:hands,objects:[],objectSeq:4,objectTime:280,modelSha256,now:300}).length,0);
const ui=fs.readFileSync('assets/js/glasses-hand-tracker-ui.js','utf8');
const mp=fs.readFileSync('assets/js/glasses-mediapipe-hands.js','utf8');
const app=fs.readFileSync('assets/js/glasses-web-simulator.js','utf8');
const page=fs.readFileSync('glasses-simulator.php','utf8');
assert.match(ui,/GelatoHeldIngredientEvidence\?\.create/);
assert.match(ui,/glassesReviewHeldObject/);
assert.match(ui,/GelatoCameraConfiguration\.capture\(1\)/);
assert.match(ui,/GelatoCameraWorkspace\?\.select\?\.\('training'\)/);
assert.match(mp,/objectSeq:otherItemId===scope\.activeItem\?\.kdsItemPublicId\?otherSeq:null/,'object frames tied to selected ticket');
assert.match(mp,/modelSha256:otherItemId===scope\.activeItem\?\.kdsItemPublicId\?otherSha:null/,'verification metadata invalidated on ticket switch');
assert.match(app,/modelSha256:state\.browserModel\.verifiedSha256/);
assert.match(page,/id="glassesHeldSuggestions"/);
assert.match(page,/id="glassesCaptureHeldObject"/);
assert.doesNotMatch(ui,/kds\.ticket\.action|check\.cancel|build\.observe/);
console.log('glasses-held-ingredient-evidence=ok');