const assert=require('node:assert/strict'),fs=require('node:fs'),path=require('node:path');
const {chromium}=require('playwright');
const base=path.resolve(__dirname,'..');
(async()=>{
const browser=await chromium.launch({headless:true,args:['--no-sandbox']});
let count=0;
const check=(yes,reason)=>{assert.ok(yes,reason);count++};
async function setup({account=7,permission='voice.agent',fakeVideo=true}={}){
 const page=await browser.newPage({viewport:{width:950,height:760},reducedMotion:'reduce'});
 const errors=[];page.on('pageerror',e=>errors.push(e.message));
 await page.route('https://gelato.test/',route=>route.fulfill({status:200,contentType:'text/html',body:'<!doctype html><html><head><meta name="viewport" content="width=device-width,initial-scale=1"></head><body class="food-monster-stage-page"><main id="food-monster-stage"></main><div id="gelato-agent-bar"><textarea id="gaInput"></textarea></div></body></html>'}));
 await page.route('https://gelato.test/js/food-monster-camera.js*',route=>route.fulfill({status:200,contentType:'text/javascript',body:fs.readFileSync(path.join(base,'js/food-monster-camera.js'),'utf8')}));
 await page.goto('https://gelato.test/');
 await page.addStyleTag({content:fs.readFileSync(path.join(base,'css/food-monster.css'),'utf8')});
 const svg=fs.readFileSync(path.join(base,'assets/food-monster/chef-mascot.svg'),'utf8');
 await page.evaluate(({svg,account,permission,fakeVideo})=>{
  window.GelatoGlobalAgent={user:{id:account,firstName:'Taylor',name:'Taylor Crew'},permissions:[permission],verifiedSpeaker:null};
  window.GelatoVoiceTurns={speak:(text,opts)=>{window.__tts={text,opts};}};
  window.fetch=async()=>({ok:true,text:async()=>svg});
  Object.defineProperty(window,'isSecureContext',{configurable:true,value:true});
  const video=HTMLMediaElement.prototype;
  video.play=async function(){if(fakeVideo){Object.defineProperty(this,'readyState',{configurable:true,value:4});Object.defineProperty(this,'videoWidth',{configurable:true,value:640});Object.defineProperty(this,'videoHeight',{configurable:true,value:480});}};
  let faces=[{box:{x:220,y:120,width:180,height:200}}];
  const d=Array.from({length:128},(_,i)=>(i%7)*.01);
  window.__faceTest={move:(x,w=180)=>{faces=[{box:{x,y:120,width:w,height:200}}]},none:()=>{faces=[]},multi:()=>{faces=[{box:{x:120,y:120,width:150,height:200}},{box:{x:360,y:120,width:160,height:200}}]},descriptor:d};
  window.faceapi={nets:{tinyFaceDetector:{loadFromUri:async()=>{}},faceLandmark68Net:{loadFromUri:async()=>{}},faceRecognitionNet:{loadFromUri:async()=>{}}},TinyFaceDetectorOptions:class{constructor(){}},detectAllFaces:async()=>faces,
   detectSingleFace:()=>({withFaceLandmarks:()=>({withFaceDescriptor:async()=>faces.length===1?{descriptor:new Float32Array(d)}:null})})};
  const track={stop(){window.__stopped=(window.__stopped||0)+1},addEventListener(){}};
  window.__media={calls:[],stream:{getTracks:()=>[track],getVideoTracks:()=>[track]}};
  Object.defineProperty(navigator,'mediaDevices',{configurable:true,value:{getUserMedia:async(arg)=>{window.__media.calls.push(arg);return window.__media.stream}}});
 },{svg,account,permission,fakeVideo});
 await page.addScriptTag({content:fs.readFileSync(path.join(base,'js/food-monster.js'),'utf8')});
 await page.locator('[data-fm-pupil]').waitFor();
 await page.locator('.fm-camera-trigger').waitFor();
 return {page,errors};
}
try{
 const {page,errors}=await setup();
 check(await page.locator('#fm-camera-dialog').count()===1,'camera settings dialog mounted');
 check(await page.locator('#fm-camera-dialog').isVisible()===false,'camera settings hidden by default');
 check(await page.evaluate(()=>window.__media.calls.length)===0,'no automatic camera use');
 await page.locator('.fm-camera-trigger').click();
 check(await page.locator('#fm-camera-dialog').isVisible(),'settings opens from monster');
 await page.locator('[data-cam="start"]').click();
 await page.waitForFunction(()=>window.GelatoFoodMonsterCamera?.active===true);
 check(await page.evaluate(()=>window.__media.calls[0].audio)===false,'camera never starts microphone');
 await page.evaluate(async()=>{window.__faceTest.move(530,230);await window.GelatoFoodMonsterCamera.scanOnce();});
 await page.waitForTimeout(250);
 check(await page.locator('#food-monster-root.fm-face-tracking').count()===1,'webcam face drives tracked state');
 let starting=await page.locator('.fm-actor').boundingBox();
 await page.evaluate(async()=>{window.__faceTest.move(40,290);await window.GelatoFoodMonsterCamera.scanOnce();});
 await page.waitForTimeout(400);
 let moved=await page.locator('.fm-actor').boundingBox();
 check(moved.x<starting.x,'floating body tracks change in face position');
 check(await page.locator('[data-fm-pupil]').getAttribute('transform')!=='translate(0 0)','eye follows face');
 await page.locator('[data-cam="enroll"]').click();
 await page.waitForFunction(()=>window.GelatoFoodMonsterCamera.enrolled===true,{timeout:12000});
 check(await page.evaluate(()=>window.GelatoFoodMonsterCamera.enrolled),'3-sample enrollment');
 for(let i=0;i<12;i++)await page.evaluate(()=>window.GelatoFoodMonsterCamera.scanOnce());
 check((await page.locator('.fm-speech').innerText()).includes('Taylor'),'face recognition personalizes greeting');
 const pass=page.locator('.fm-camera-password input');
 await pass.fill('sample passphrase 123!');
 await page.locator('[data-cam="save"]').click();
 await page.waitForFunction(()=>document.querySelector('.fm-camera-message').textContent.includes('Encrypted face profile saved'));
 const persisted=await page.evaluate(()=>localStorage.getItem('gelato.fm.encrypted-face.v1.7'));
 check(persisted&&!persisted.includes('"descriptor"')&&!persisted.includes('Taylor'),'encrypted biometric storage');
 await page.locator('[data-cam="forget"]').click();
 check(await page.evaluate(()=>!window.GelatoFoodMonsterCamera.enrolled),'forget active biometric');
 await pass.fill('sample passphrase 123!');
 await page.locator('[data-cam="unlock"]').click();
 await page.waitForFunction(()=>window.GelatoFoodMonsterCamera.enrolled===true);
 check(await page.evaluate(()=>window.GelatoFoodMonsterCamera.enrolled),'encrypted template unlock');
 await page.locator('[data-cam="delete"]').click();
 check(await page.evaluate(()=>localStorage.getItem('gelato.fm.encrypted-face.v1.7')===null),'delete biometric template');
 await page.evaluate(()=>window.dispatchEvent(new CustomEvent('gelato-verified-speaker',{detail:{sessionUserMatch:false,userId:8,name:'Other'}})));
 check((await page.locator('.fm-speech').innerText()).includes('Taylor'),'other speaker cannot replace session identity');
 await page.locator('[data-cam="stop"]').click();
 check(await page.evaluate(()=>window.__stopped>0&&!window.GelatoFoodMonsterCamera.active),'stopping releases real camera tracks');
 check(errors.length===0,'no browser exceptions: '+errors.join(','));
 await page.close();
 const {page:voice,errors:voiceErrors}=await setup({account:11});
 await voice.locator('.fm-camera-trigger').click();
 await voice.locator('[data-pref="speak"]').check();
 await voice.evaluate(()=>{window.GelatoGlobalAgent.verifiedSpeaker={sessionUserMatch:true,userId:11,name:'Taylor'};window.dispatchEvent(new CustomEvent('gelato-verified-speaker',{detail:{sessionUserMatch:true,userId:11,name:'Taylor'}}));});
 check((await voice.locator('.fm-speech').innerText()).includes('Taylor'),'verified own speaker receives greeting');
 check((await voice.evaluate(()=>window.__tts?.text||'')).includes('Taylor'),'spoken greeting only with user opt-in');
 check(voiceErrors.length===0,'voice scenario without errors');
 await voice.close();
 console.log('FM-G3 mocked webcam, expression, face & voice privacy: PASS ('+count+' assertions)');
}finally{await browser.close();}
})().catch(e=>{console.error(e.stack||e);process.exit(1)});
