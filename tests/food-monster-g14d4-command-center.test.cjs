'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs');
const vm=require('node:vm');
const code=fs.readFileSync('js/agent-canvas.js','utf8');
const a=code.indexOf('  function pilotCommandCenter(data) {');
const b=code.indexOf('  function structuredCard(',a);
assert(a>=0&&b>a,'integrated pilot command center exists');
const esc=v=>String(v??'').replace(/[&<>"']/g,c=>({'&':'&amp;','<':'&lt;','>':'&gt;','"':'&quot;',"'":'&#39;'}[c]));
const render=vm.runInNewContext('('+code.slice(a,b).trim()+')',{esc});
const gates=['microphone','transcription','handoff','camera','timeclock','kds','recovery'];
const sample={active:true,closed:false,items:gates.map(gate=>({gate,status:'pass'})),readiness:{unresolvedIssues:0}};
let n=0;function ok(condition,label){assert.ok(condition,label);n++;}
const all=render(sample);
ok(all.includes('Pilot command center'),'title');
ok(all.includes('independent physical certification'),'passing state not certified');
ok((all.match(/ — pass/g)||[]).length===7,'seven checks');
ok(all.includes('authorized self-view'),'self-view scoped');
ok(all.includes('Super Admin only'),'team scope');
ok(!all.includes('PRIVATE_TEST'), 'no unrelated personal data');
const failed=render({...sample,items:sample.items.map((x,i)=>i?x:{gate:x.gate,status:'failed<script>'}),readiness:{unresolvedIssues:1}});
ok(failed.includes('kitchen pilot fixes'),'repairs first');
ok(!failed.includes('<script>'),'unknown state never reflected');
ok(failed.includes('not_tested'),'invalid status fails closed');
const inactive=render({...sample,active:false,closed:true});
ok(inactive.includes('start kitchen pilot'),'closed run guidance');
const malicious=render({...sample,items:[{gate:'camera',status:'blocked',title:'<img src=x onerror=alert(1)>'}]});
ok(!malicious.includes('<img'),'no injection');
ok(!/fetch\(|post\(|getUserMedia\(|localStorage\.|sessionStorage\./.test(code.slice(a,b)),'render read only');
ok(code.includes('readinessHtml+pilotCommandCenter(data)'),'render integrated');
ok(code.includes('Field certification pending independent real-device review'),'certification boundary');
console.log('FM-G14D4 command center PASS ('+n+' assertions)');
