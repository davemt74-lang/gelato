'use strict';
const assert=require('node:assert/strict'),fs=require('node:fs');
const {create}=require('../assets/js/glasses-hand-box-stabilizer.js');
const hand=(slot,id,x,at)=>({slot,trackId:id,status:'tracking',seen:at,bbox:{x,y:.2,width:.2,height:.2}});
const s=create();
let a=s.step([hand(1,'left',.1,1000),hand(2,'right',.7,1000)],1000);
assert.deepEqual(a.map(x=>x.trackId),['left','right'],'gate 1: two independent hands');
a=s.step([hand(1,'left',.13,1100),hand(2,'right',.68,1100)],1100);
assert.ok(a[0].bbox.x>.1&&a[0].bbox.x<.13&&a[1].bbox.x<.7&&a[1].bbox.x>.68,'gate 2: box smoothing');
a=s.step([hand(1,'left',.55,1200)],1200);
assert.equal(a[0].bbox.x,.55,'gate 3: rapid motion responsive');
a=s.step([{slot:1,trackId:'left',status:'occluded',seen:1200}],1290);
assert.equal(a[0].status,'reacquiring');assert.equal(a[0].held,true,'gate 4: display-only reacquisition');
assert.deepEqual(s.step([{slot:1,trackId:'left',status:'occluded',seen:1200}],1381),[],'gate 5: timeout');
assert.equal(s.step([hand(1,'new',.08,1400)],1400)[0].bbox.x,.08,'gate 6: new identity resets motion');
assert.deepEqual(s.step([hand(1,'new',.09,1399)],1399),[],'gate 7: replay rejected');
assert.deepEqual(s.step([{slot:1,trackId:'bad',status:'tracking',seen:1500,bbox:{x:-.1,y:0,width:.5,height:.5}}],1500),[],'gate 8: invalid box');
s.reset();assert.deepEqual(s.step([{slot:1,trackId:'new',status:'occluded',seen:1700}],1750),[],'gate 9: reset clears visual ghost');
const source=fs.readFileSync('assets/js/glasses-hand-box-stabilizer.js','utf8');
const ui=fs.readFileSync('assets/js/glasses-hand-tracker-ui.js','utf8');
const html=fs.readFileSync('glasses-simulator.php','utf8');
assert.doesNotMatch(source,/\bfetch\s*\(|getUserMedia|postMessage|localStorage|setInterval|setTimeout|kds\.|build\.observe/);
assert.match(ui,/GelatoHandBoxStabilizer/);
assert.match(ui,/visualBoxes=visual\?visual\.step\(current\.tracks,lastFrame\)/);
assert.match(ui,/for\(const t of visualBoxes\)/);
assert.match(html,/glasses-hand-box-stabilizer\.js/);
assert.match(html,/glasses-hand-tracker-ui\.js/);
console.log('285d1-display-stabilization-gates=10/10');
