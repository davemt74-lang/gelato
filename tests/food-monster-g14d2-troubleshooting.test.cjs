'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs');
const vm=require('node:vm');
const code=fs.readFileSync('js/agent-canvas.js','utf8');
const start=code.indexOf('  function pilotTroubleshooting(rows) {');
const end=code.indexOf('  // Strictly project existing local diagnostic snapshots',start);
assert(start>=0&&end>start);
const part=code.slice(start,end);
const esc=x=>String(x).replace(/[&<>"']/g,'');
const advice=vm.runInNewContext(part+';pilotTroubleshooting',[].length?{}:{esc});
const test=(rows)=>advice(rows);
let count=0;
function ok(yes,why){assert.ok(yes,why);count++;}
ok(test([['Speech recognition','blocked'],['Speech-service error','not-allowed']])[0].subject==='Microphone permission','permission advice');
ok(test([['Speech recognition','failed'],['Speech-service error','audio-capture']])[0].subject==='Microphone source','audio error advice');
ok(test([['Speech recognition','active'],['Speech-service error','network']])[0].subject==='Speech service','network advice');
ok(test([['Speech recognition','failed'],['Speech-service error','retry-limit']])[0].subject==='Speech recovery','retry exhaustion advice');
ok(test([['Speech recognition','retrying'],['Speech-service error','none']])[0].subject==='Speech recovery','retrying advice');
ok(test([['Speech recognition','unavailable'],['Speech-service error','unavailable']])[0].subject==='Speech diagnostics','unknown advice');
ok(test([['Speech recognition','active'],['Speech-service error','none'],['KDS listening','always'],['KDS mic active','No / unavailable']]).some(x=>x.subject==='KDS voice'),'KDS mismatch');
ok(test([['Speech recognition','active'],['Speech-service error','none'],['Camera 2','inactive · failed · retries 3']]).some(x=>x.subject==='Camera 2'),'camera failure');
ok(test([['Speech recognition','active'],['Speech-service error','none']]).length===0,'no false device readiness claim');
ok(test([['Speech recognition','active'],['Speech-service error','none'],['Camera 1','active · ready · retries 0']]).length===0,'ready camera no warning');
ok(test(Array.from({length:20},(_,i)=>['Camera '+(i+1),'inactive · failed · retries 3'])).length<=8,'bounded output');
ok(!/fetch\(|post\(|getUserMedia\(|localStorage\.|sessionStorage\./.test(part),'advice does not access external device or storage');
ok(code.includes('pilotTroubleshootingHtml(pilotDeviceSummary())'),'integrated in existing sidebar');
ok(code.includes('No repairs or field results were applied'),'non-authoritative framing');
console.log('FM-G14D2 assisted troubleshooting PASS ('+count+' assertions)');
